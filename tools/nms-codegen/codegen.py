"""Shared helpers that write typed NMS classes into nms/<module> and the tables that NMSClassRegistry reads."""
import os
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
NMS_SOURCES = ROOT / "spigot/src/main/java/dev/marulabs/commandlib/util/nms"
BASE_PACKAGE = "dev.marulabs.commandlib.util.nms"
NL = "\n"


def _wrapper_packages():
    """Maps each wrapper's simple name to its package."""
    packages = {}
    for directory, _, files in os.walk(NMS_SOURCES):
        relative = Path(directory).relative_to(NMS_SOURCES).as_posix()
        package = BASE_PACKAGE if relative == "." else BASE_PACKAGE + "." + relative.replace("/", ".")
        for file in files:
            packages[file[:-len(".java")]] = package
    return packages


WRAPPER_PACKAGES = _wrapper_packages()
IMPLICIT_IMPORTS = [
    ("ArgumentType<", "com.mojang.brigadier.arguments.ArgumentType"),
    ("CommandContext<", "com.mojang.brigadier.context.CommandContext"),
    ("CommandSyntaxException e", "com.mojang.brigadier.exceptions.CommandSyntaxException"),
    ("UncheckedCommandSyntaxException", BASE_PACKAGE + ".exception.UncheckedCommandSyntaxException"),
    ("List<", "java.util.List"),
    ("Collectors.", "java.util.stream.Collectors"),
    ("Supplier<", "java.util.function.Supplier"),
    ("@Nullable", "org.jetbrains.annotations.Nullable"),
]


def module_package(module):
    return "dev.marulabs.commandlib.nms." + module.replace("-", "_").replace(".", "_")


def source_directory(module):
    return ROOT / "nms" / module / "src/main/java" / module_package(module).replace(".", "/")


def clear(module):
    """Deletes the generated sources of the module, so classes the scripts no longer write do not linger."""
    shutil.rmtree(source_directory(module), ignore_errors=True)


def write_source(module, package, name, source):
    path = ROOT / "nms" / module / "src/main/java" / package.replace(".", "/") / f"{name}.java"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source, encoding="utf-8", newline=NL)


def write(module, wrapper, body, imports=()):
    """
    Writes the typed implementation of a wrapper such as NMSArgumentDimension and returns its simple name. Wrappers
    that the body mentions are imported automatically.
    """
    name = f"{wrapper}_{module_package(module).split('.')[-1]}"
    package = module_package(module)

    all_imports = set(imports)
    all_imports.add(f"{WRAPPER_PACKAGES[wrapper]}.{wrapper}")
    for other, other_package in WRAPPER_PACKAGES.items():
        if other != wrapper and re.search(r"\b" + other + r"\b", body):
            all_imports.add(f"{other_package}.{other}")
    for marker, implicit in IMPLICIT_IMPORTS:
        if marker in body:
            all_imports.add(implicit)
    import_lines = NL.join(f"import {x};" for x in sorted(all_imports, key=lambda x: (not x.startswith("com."), x)))

    write_source(module, package, name,
                 f"package {package};{NL}{NL}{import_lines}{NL}{NL}"
                 f"public class {name} extends {wrapper} {{{NL}{body.rstrip()}{NL}}}{NL}")
    return name


def write_class_list(module, names):
    """
    Writes TypedNmsClasses, the list of the module's typed classes. NMSClassRegistry maps each class to the wrapper it
    extends.
    """
    package = module_package(module)
    separator = f",{NL}{' ' * 23}"
    write_source(module, package, "TypedNmsClasses", f"""package {package};

import java.util.List;

/**
 * The typed classes of this module, which NMSClassRegistry maps to the wrappers they extend. Generated by
 * {{@code tools/nms-codegen}}.
 */
public final class TypedNmsClasses {{
    private TypedNmsClasses() {{
    }}

    public static List<Class<?>> classes() {{
        return List.of({separator.join(f"{x}.class" for x in sorted(names))});
    }}
}}
""")


def write_module_table(modules):
    """
    Writes TypedNmsModules, the table of typed NMS modules that NMSClassRegistry reads. A Paper module also ships its
    reobfuscated classes in the <package>_spigot package.
    """
    entries = []
    for module, spec in modules.items():
        package = module_package(module).split(".")[-1]
        entries.append(f'new NMSClassRegistry.TypedModule("{package}", "{spec.lower}", "{spec.upper}")')
        if module.startswith("paper-"):
            entries.append(f'new NMSClassRegistry.TypedModule("{package}_spigot", "{spec.lower}", "{spec.upper}")')
    separator = f",{NL}{' ' * 12}"
    path = NMS_SOURCES / "TypedNmsModules.java"
    path.write_text(f"""package {BASE_PACKAGE};

import java.util.List;

/**
 * The typed NMS modules bundled into the spigot jar (see {{@code docs/agents/nms-build.md}}). Generated by
 * {{@code tools/nms-codegen/generate.py}} from its module table; edit the table and regenerate instead of this file.
 */
final class TypedNmsModules {{
    static final List<NMSClassRegistry.TypedModule> MODULES = List.of(
            {separator.join(entries)});

    private TypedNmsModules() {{
    }}
}}
""", encoding="utf-8", newline=NL)
